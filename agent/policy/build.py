"""The Lab Watch sandbox's network policy preset, as data, and its YAML file.

    python3 -m agent.policy.build            write agent/policy/labwatch-bench.yaml
    python3 -m agent.policy.build --check    exit 1 if the committed file differs
    python3 -m agent.policy.build --bridge-ip 172.18.0.1 --stdout

The preset is in the NemoClaw custom-preset format (a `preset:` block plus
`network_policies:`), applied with `nemoclaw <sandbox> policy add --from-file`.
It allows the bench endpoint (lane A, port 8765) on the docker bridge address
only: the interface's read-only routes and its two side-effect routes, from
python3 (the skill's client) only.

Local inference (host.openshell.internal:8000, GET /v1/models and POST
/v1/chat/completions) is not in this preset: OpenShell composes that entry
itself from the inference provider (key _provider_nemoclaw_local_v1_*), and a
second entry for the same host:port is refused ("network endpoint ambiguity").
INFERENCE_RULES below records what that provider entry must allow.

No other host. Every other preset and baseline entry is removed by apply.sh.
There is no Telegram entry (the GB10 has no internet; the bench's own sender
reaches Telegram through the laptop relay) and no tracker entry, ever.
"""

import argparse
import os
import sys

BRIDGE_HOST = "host.openshell.internal"
DEFAULT_BRIDGE_IP = "172.18.0.1"
BENCH_PORT = 8765
INFERENCE_PORT = 8000
PRESET_NAME = "labwatch-bench"
HERE = os.path.dirname(os.path.abspath(__file__))
YAML_PATH = os.path.join(HERE, "labwatch-bench.yaml")

# The interface's routes. Query strings (?open=1, ?since=, ?ref=) are not part
# of the path the policy matches.
BENCH_RULES = (
    ("GET", "/health"),
    ("GET", "/board"),
    ("GET", "/incidents"),
    ("GET", "/incidents/*"),
    ("GET", "/runs"),
    ("GET", "/runs/*"),
    ("GET", "/events"),
    ("GET", "/show"),
    ("POST", "/run"),
    ("POST", "/board/test"),
)
BENCH_BINARIES = ("/usr/bin/python3", "/usr/bin/python3.13")

INFERENCE_RULES = (
    ("GET", "/v1/models"),
    ("POST", "/v1/chat/completions"),
)


def policy(bridge_ip=DEFAULT_BRIDGE_IP):
    """The preset as plain dicts and lists, in output order."""
    def endpoint(port, rules):
        return {
            "host": BRIDGE_HOST,
            "port": port,
            "protocol": "rest",
            "enforcement": "enforce",
            "allowed_ips": [bridge_ip + "/32"],
            "rules": [{"allow": {"method": m, "path": p}} for m, p in rules],
        }

    return {
        "preset": {
            "name": PRESET_NAME,
            "description": "Lab Watch: the bench endpoint on the docker bridge only",
        },
        "network_policies": {
            "labwatch_bench": {
                "name": "labwatch_bench",
                "endpoints": [endpoint(BENCH_PORT, BENCH_RULES)],
                "binaries": [{"path": b} for b in BENCH_BINARIES],
            },
        },
    }


def _scalar(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return '"%s"' % v.replace("\\", "\\\\").replace('"', '\\"')


def to_yaml(obj, indent=0):
    """A small block-style YAML emitter for dicts, lists and scalars."""
    pad = "  " * indent
    out = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if isinstance(v, (dict, list)):
                out.append("%s%s:" % (pad, k))
                out.extend(to_yaml(v, indent + 1))
            else:
                out.append("%s%s: %s" % (pad, k, _scalar(v)))
    elif isinstance(obj, list):
        for item in obj:
            if isinstance(item, (dict, list)):
                lines = to_yaml(item, indent + 1)
                first = lines[0].lstrip()
                out.append("%s- %s" % (pad, first))
                out.extend(lines[1:])
            else:
                out.append("%s- %s" % (pad, _scalar(item)))
    return out


def render(bridge_ip=DEFAULT_BRIDGE_IP):
    head = ["# Generated by python3 -m agent.policy.build; edit build.py, not this file.",
            "# NemoClaw custom preset: nemoclaw <sandbox> policy add --from-file <this> --yes"]
    return "\n".join(head + to_yaml(policy(bridge_ip))) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--bridge-ip", default=DEFAULT_BRIDGE_IP)
    ap.add_argument("--check", action="store_true", help="compare with the committed file")
    ap.add_argument("--stdout", action="store_true", help="print instead of writing")
    a = ap.parse_args(argv)
    text = render(a.bridge_ip)
    if a.stdout:
        sys.stdout.write(text)
        return 0
    if a.check:
        try:
            with open(YAML_PATH, encoding="utf-8") as f:
                same = f.read() == text
        except OSError:
            same = False
        print("up to date" if same else "differs: run python3 -m agent.policy.build")
        return 0 if same else 1
    with open(YAML_PATH, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
